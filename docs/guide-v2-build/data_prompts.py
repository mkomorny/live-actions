"""The prompt library for Genius Guide v2, Book 3.

Every entry is a prompt you can paste straight into Genius, tagged with how hard
it is, which chat model suits it best, and which live_* actions it is expected to
reach for. The `actions` list is checked against the real tool surface at build
time, so a prompt can't reference an action that doesn't exist.

Complexity:
  Starter      - one action, no prerequisites, safe to run on any Set
  Intermediate - a few actions chained, or one action with real parameters
  Advanced     - multi-step, reads state then acts on it, touches several tracks
  Expert       - closed loops, verification passes, or long autonomous builds

Model tags are guidance, not hard requirements -- see Book 1 for the reasoning.
"""
